#!/usr/bin/env node

/**
 * OpenClaw WebSocket Connection Test Script
 * 
 * Usage:
 *   1. Start backend server: cd code/backend && npm run dev
 *   2. Run this script: node test-openclaw-connection.js
 *   3. Follow the interactive prompts
 */

const io = require('socket.io-client')
const readline = require('readline')

const BACKEND_URL = process.env.BACKEND_URL || 'http://localhost:3000'
const JWT_TOKEN = process.env.TEST_JWT_TOKEN || ''

if (!JWT_TOKEN) {
  console.error('❌ ERROR: Set TEST_JWT_TOKEN environment variable')
  console.error('   Get a token by logging in via the frontend or API')
  process.exit(1)
}

console.log('🔗 Connecting to Arena backend...')
console.log(`   URL: ${BACKEND_URL}`)
console.log(`   Token: ${JWT_TOKEN.substring(0, 20)}...`)

const socket = io(BACKEND_URL, {
  auth: { token: JWT_TOKEN },
  transports: ['websocket']
})

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout
})

socket.on('connect', () => {
  console.log('✅ Connected to backend')
  console.log(`   Socket ID: ${socket.id}`)
  showMenu()
})

socket.on('connect_error', (err) => {
  console.error('❌ Connection failed:', err.message)
  process.exit(1)
})

socket.on('error', (data) => {
  console.error(`❌ Server error: ${data.code} - ${data.message}`)
})

// OpenClaw events
socket.on('openclaw_connect_success', () => {
  console.log('✅ OpenClaw connection registered!')
})

socket.on('openclaw_connected', (data) => {
  console.log('🤖 OpenClaw connected to match:', data)
})

socket.on('openclaw_disconnected', (data) => {
  console.log('🔌 OpenClaw disconnected from match:', data.match_id)
})

socket.on('request_bot_suggestion', (data) => {
  console.log('\n📊 SUGGESTION REQUEST RECEIVED')
  console.log(`   Match: ${data.match_id}`)
  console.log(`   Round: ${data.round}`)
  console.log(`   Player HP: ${data.player_bot.hp}`)
  console.log(`   Player Energy: ${data.player_bot.energy}`)
  console.log(`   Opponent HP: ${data.opponent_bot.hp}`)
  console.log(`   Time Limit: ${data.time_limit_ms}ms`)
  console.log(`   Skills: ${data.player_bot.skills.map(s => s.id).join(', ')}`)
  
  // Auto-respond with mock suggestion
  setTimeout(() => {
    console.log('🤖 Sending mock suggestion...')
    socket.emit('bot_suggestion_response', {
      match_id: data.match_id,
      suggestion: {
        skill_id: data.player_bot.skills[0]?.id || 'basic_attack',
        skill_name: 'Mock Skill',
        reasoning: [
          'This is a test suggestion',
          'Generated by test script',
          'Not real AI analysis'
        ],
        confidence: 0.85,
        risk_level: 'medium',
        expected_damage: 25,
        counters: ['shield', 'dodge']
      },
      response_time_ms: 1200
    })
  }, 1000)
})

socket.on('coaching_message', (data) => {
  console.log('\n💬 COACHING MESSAGE')
  console.log(`   Match: ${data.match_id}`)
  console.log(`   Message: "${data.message}"`)
  console.log(`   Context: HP=${data.context.current_hp}, Energy=${data.context.current_energy}, Round=${data.context.round}`)
  
  // Auto-respond
  setTimeout(() => {
    console.log('🤖 Sending mock coaching response...')
    socket.emit('coaching_response', {
      match_id: data.match_id,
      message: `Mock response to: "${data.message}". This is a test coaching message.`
    })
  }, 500)
})

function showMenu() {
  console.log('\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━')
  console.log('OpenClaw Test Menu')
  console.log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━')
  console.log('1. Connect as OpenClaw bot')
  console.log('2. Disconnect OpenClaw bot')
  console.log('3. Send test suggestion response')
  console.log('4. Send test coaching response')
  console.log('5. Exit')
  console.log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━')
  
  rl.question('Choose option: ', (answer) => {
    handleChoice(answer.trim())
  })
}

function handleChoice(choice) {
  switch (choice) {
    case '1':
      console.log('🤖 Connecting as OpenClaw...')
      socket.emit('openclaw_connect', {
        bot_name: 'TestBot',
        model: 'claude-sonnet-4',
        provider: 'anthropic',
        session_key: 'test-session-' + Date.now()
      })
      setTimeout(showMenu, 1000)
      break
      
    case '2':
      console.log('🔌 Disconnecting OpenClaw...')
      socket.emit('openclaw_disconnect')
      setTimeout(showMenu, 500)
      break
      
    case '3':
      rl.question('Enter match_id: ', (matchId) => {
        console.log('📤 Sending test suggestion...')
        socket.emit('bot_suggestion_response', {
          match_id: matchId,
          suggestion: {
            skill_id: 'power_strike',
            skill_name: 'Power Strike',
            reasoning: [
              'Opponent has low HP (35%)',
              'High damage potential this round',
              'Energy cost is acceptable'
            ],
            confidence: 0.92,
            risk_level: 'low',
            expected_damage: 45,
            counters: ['shield', 'dodge', 'reflect']
          },
          response_time_ms: 1450
        })
        setTimeout(showMenu, 500)
      })
      break
      
    case '4':
      rl.question('Enter match_id: ', (matchId) => {
        console.log('📤 Sending test coaching response...')
        socket.emit('coaching_response', {
          match_id: matchId,
          message: 'Focus on energy management. Your opponent is low on HP but has high energy for a counter-attack. Consider a defensive skill to bait their ultimate, then finish them next round.'
        })
        setTimeout(showMenu, 500)
      })
      break
      
    case '5':
      console.log('👋 Exiting...')
      socket.disconnect()
      rl.close()
      process.exit(0)
      break
      
    default:
      console.log('❌ Invalid choice')
      showMenu()
  }
}

// Handle cleanup
process.on('SIGINT', () => {
  console.log('\n👋 Disconnecting...')
  socket.disconnect()
  rl.close()
  process.exit(0)
})
